#!/usr/bin/env node
/**
 * Builds src/io/lens/lensfun-subset.json from the lensfun database (CC BY-SA 3.0,
 * https://github.com/lensfun/lensfun): the camera makers' own lenses for the common mounts plus
 * popular third-party mirrorless lenses, with their distortion, TCA and vignetting calibrations
 * (vignetting at infinity focus and apertures up to f/11, beyond which it is nearly flat), numbers
 * rounded to 4 significant digits. Loaded lazily, only for non-DNG raw files.
 * Run: node scripts/build-lensfun-subset.mjs
 */
import fs from 'node:fs';

const BASE = 'https://raw.githubusercontent.com/lensfun/lensfun/master/data/db/';
const FILES = {
  'mil-sony.xml': ['Sony'],
  'mil-canon.xml': ['Canon'],
  'mil-nikon.xml': ['Nikon'],
  'mil-fujifilm.xml': ['Fujifilm', 'Fujian'],
  'mil-panasonic.xml': ['Panasonic', 'Leica'],
  'mil-olympus.xml': ['Olympus', 'OM Digital Solutions'],
  'om-system.xml': ['OM Digital Solutions', 'Olympus'],
  'mil-sigma.xml': ['Sigma'],
  'mil-tamron.xml': ['Tamron'],
  'slr-canon.xml': ['Canon'],
  'slr-nikon.xml': ['Nikon'],
};

const round4 = (x) => +(+x).toPrecision(4);
const attrs = (s) => Object.fromEntries([...s.matchAll(/(\w+)="([^"]*)"/g)].map((m) => [m[1], m[2]]));
const text = (block, tag) => {
  const m = block.match(new RegExp(`<${tag}(?:\\s[^>]*)?>([^<]*)</${tag}>`));
  return m ? m[1].trim() : undefined;
};

const lenses = [];
const cameras = [];
for (const [file, makers] of Object.entries(FILES)) {
  const xml = await (await fetch(BASE + file)).text();
  for (const m of xml.matchAll(/<camera>([\s\S]*?)<\/camera>/g)) {
    const b = m[1];
    const crop = text(b, 'cropfactor');
    if (crop) cameras.push({ maker: text(b, 'maker'), model: text(b, 'model'), crop: round4(crop) });
  }
  for (const m of xml.matchAll(/<lens>([\s\S]*?)<\/lens>/g)) {
    const b = m[1];
    const maker = text(b, 'maker');
    if (!makers.some((x) => maker?.toLowerCase().startsWith(x.toLowerCase()))) continue;
    const dist = [], tca = [], vigAll = [];
    for (const d of b.matchAll(/<distortion ([^>]*)\/>/g)) {
      const a = attrs(d[1]);
      if (a.model === 'ptlens') dist.push([round4(a.focal), 'ptlens', round4(a.a ?? 0), round4(a.b ?? 0), round4(a.c ?? 0)]);
      else if (a.model === 'poly3') dist.push([round4(a.focal), 'poly3', round4(a.k1 ?? 0)]);
      else if (a.model === 'poly5') dist.push([round4(a.focal), 'poly5', round4(a.k1 ?? 0), round4(a.k2 ?? 0)]);
    }
    for (const d of b.matchAll(/<tca ([^>]*)\/>/g)) {
      const a = attrs(d[1]);
      if (a.model === 'poly3') tca.push([round4(a.focal), round4(a.vr ?? 1), round4(a.cr ?? 0), round4(a.br ?? 0), round4(a.vb ?? 1), round4(a.cb ?? 0), round4(a.bb ?? 0)]);
      else if (a.model === 'linear') tca.push([round4(a.focal), round4(a.kr ?? 1), 0, 0, round4(a.kb ?? 1), 0, 0]);
    }
    for (const d of b.matchAll(/<vignetting ([^>]*)\/>/g)) {
      const a = attrs(d[1]);
      if (a.model === 'pa') vigAll.push({ f: +a.focal, ap: +a.aperture, dist: +(a.distance ?? 1000), k: [round4(a.k1 ?? 0), round4(a.k2 ?? 0), round4(a.k3 ?? 0)] });
    }
    // Vignetting: the farthest focus distance per (focal, aperture).
    const best = new Map();
    for (const v of vigAll) {
      const k = `${v.f}/${v.ap}`;
      if (!best.has(k) || best.get(k).dist < v.dist) best.set(k, v);
    }
    const vig = [...best.values()].filter((v) => v.ap <= 11).map((v) => [round4(v.f), round4(v.ap), ...v.k]);
    if (!dist.length && !tca.length && !vig.length) continue;
    const crop = text(b, 'cropfactor');
    lenses.push({ maker, model: text(b, 'model'), crop: crop ? round4(crop) : 1, dist, tca, vig });
  }
}

const out = {
  attribution: 'Lens calibrations from the lensfun database (https://github.com/lensfun/lensfun), CC BY-SA 3.0. Subset generated by scripts/build-lensfun-subset.mjs.',
  cameras,
  lenses,
};
fs.mkdirSync('src/io/lens', { recursive: true });
fs.writeFileSync('src/io/lens/lensfun-subset.json', JSON.stringify(out));
console.log(`${lenses.length} lenses, ${cameras.length} cameras, ${(JSON.stringify(out).length / 1024).toFixed(0)} KB`);
